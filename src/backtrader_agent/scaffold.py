def _nested(value, *parts, default=None):
    current = value
    for part in parts:
        if not isinstance(current, dict) or part not in current:
            return default
        current = current[part]
    return current


def _finite_number(value):
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def _last_series_value(series):
    if isinstance(series, dict) and series:
        return series[list(series)[-1]]
    if isinstance(series, (list, tuple)) and series:
        return series[-1]
    return series


def _positions_value_total(series):
    entry = _last_series_value(series)
    if isinstance(entry, (list, tuple)):
        return _finite_number(sum(_finite_number(item) or 0.0 for item in entry))
    if isinstance(entry, dict):
        return _finite_number(
            sum(_finite_number(item) or 0.0 for item in entry.values())
        )
    return _finite_number(entry)


def _safe_analyzer(base):
    class _SafeAnalyzer(base):
        def _next(self):
            try:
                super()._next()
            except Exception:
                pass

        def next(self):
            try:
                super().next()
            except Exception:
                pass

        def _stop(self):
            try:
                super()._stop()
            except Exception:
                pass

        def stop(self):
            try:
                super().stop()
            except Exception:
                pass

    return _SafeAnalyzer


def _trade_analyzer_subset(trade):
    won_total = float(_nested(trade, "won", "pnl", "total", default=0.0) or 0.0)
    lost_total = float(_nested(trade, "lost", "pnl", "total", default=0.0) or 0.0)
    if lost_total:
        profit_factor = _finite_number(won_total / abs(lost_total))
    else:
        profit_factor = None
    return {{
        "profit_factor": profit_factor,
        "avg_holding_bars": _finite_number(_nested(trade, "len", "average")),
        "max_consecutive_wins": _finite_number(
            _nested(trade, "streak", "won", "longest", default=0)
        ),
        "max_consecutive_losses": _finite_number(
            _nested(trade, "streak", "lost", "longest", default=0)
        ),
    }}


