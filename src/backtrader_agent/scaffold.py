def _sizing_assembly(sizing: Optional[Dict[str, Any]]) -> str:
    """Render the fixed cerebro.addsizer assembly for the validated sizing block.

    Returns an empty string when sizing is null so a spec without a sizing
    block keeps Backtrader's default sizer, exactly as before R24.

    The bound engine fork's ``Cerebro.addsizer`` takes the sizer *class*
    plus constructor arguments (it instantiates in ``runstrategies``), so
    the assembly passes ``bt.sizers.FixedSize`` / ``bt.sizers.PercentSizer``
    as classes; this form also works on stock Backtrader.
    """

    if not sizing:
        return ""
    if sizing["method"] == "fixed":
        return (
            "cerebro.addsizer(bt.sizers.FixedSize, "
            f"stake={sizing['fixed_size']!r})\n    "
        )
    return (
        "cerebro.addsizer(bt.sizers.PercentSizer, "
        f"percents={sizing['percent']!r})\n    "
    )


