class ArtifactRenderer:
    def __init__(self, state_root: Path) -> None:
        self.state_root = Path(state_root)

    def render(
        self,
        session_id: str,
        spec: StrategySpec,
        dataset: Dict[str, Any],
        *,
        draft_root: Optional[Path] = None,
    ) -> Dict[str, Any]:
        if not SESSION_RE.fullmatch(session_id):
            raise AgentError("BTAG-SESSION-ID", "session ID is malformed")
        if dataset.get("dataset_id") != spec.value["dataset_id"]:
            raise AgentError(
                "BTAG-RENDER-DATASET", "StrategySpec dataset ID does not match"
            )
        revision = hash_object(
            {
                "spec_hash": spec.spec_hash,
                "dataset_hash": dataset.get("manifest_hash"),
                "renderer": "scaffold-v1",
            }
        )[:20]
        if draft_root is None:
            draft_root = self.state_root / "sessions" / session_id / "drafts" / revision
        else:
            # Renderer-owned private drafts may live elsewhere under the state
            # root (sweep cells render into their sealed cell directory); the
            # provenance record keeps the state-relative location bound either
            # way.
            draft_root = Path(draft_root)
        if spec.profile == "python_bundle":
            file_contents = {
                "config.yaml": _config_source(spec, dataset).encode("utf-8"),
                f"strategy_{spec.module_slug}.py": _strategy_source(spec).encode(
                    "utf-8"
                ),
                "run.py": _runner_source(spec, dataset).encode("utf-8"),
            }
            roles = {
                "config.yaml": "config",
                f"strategy_{spec.module_slug}.py": "strategy",
                "run.py": "runner",
            }
            entrypoint = "run.py"
        else:
            name = f"test_{spec.slug}.py"
            file_contents = {
                name: _render_single_test_source(
                    _strategy_source(spec),
                    custom_feed_source=_pandas_custom_feed_source(dataset),
                    cash=float(spec.value.get("cash", 100000.0)),
                    commission=float(spec.value.get("commission", 0.0)),
                    sizing_assembly=_sizing_assembly(spec.value.get("sizing")),
                ).encode("utf-8")
            }
            roles = {name: "strategy"}
            entrypoint = name
        draft_root.mkdir(parents=True, exist_ok=True)
        files: List[Dict[str, Any]] = []
        for relative_path, content in sorted(file_contents.items()):
            destination = draft_root / relative_path
            create_or_verify_bytes(
                destination,
                content,
                conflict_code="BTAG-DRAFT-CONFLICT",
                conflict_message="draft revision has conflicting bytes",
            )
            files.append(
                {
                    "path": relative_path,
                    "role": roles[relative_path],
                    "sha256": sha256_bytes(content),
                    "bytes": len(content),
                }
            )
        portable = {
            "schema_version": "artifact-manifest-v1",
            "artifact_id": f"artifact-{revision}",
            "slug": spec.slug,
            "spec_hash": spec.spec_hash,
            "dataset_id": dataset["dataset_id"],
            "output_profile": spec.profile,
            "files": files,
            "extensions": {
                "backtrader_agent": {
                    "generated_by": "backtrader-agent",
                    "renderer_version": "scaffold-v1",
                    "session_id": session_id,
                    "archetype": spec.archetype,
                    "dataset_manifest_hash": dataset["manifest_hash"],
                    "entrypoint": entrypoint,
                }
            },
        }
        portable["artifact_hash"] = hash_object(portable)
        manifest_path = draft_root / "artifact-manifest.json"
        create_or_verify_json(
            manifest_path,
            portable,
            conflict_code="BTAG-DRAFT-MANIFEST",
            conflict_message="draft manifest conflicts",
        )
        state_root = self.state_root.resolve()
        resolved_draft = draft_root.resolve(strict=True)
        try:
            draft_relative = resolved_draft.relative_to(state_root).as_posix()
        except ValueError as exc:
            raise AgentError(
                "BTAG-DRAFT-PATH", "private draft must remain inside state root"
            ) from exc
        record_payload: Dict[str, Any] = {
            "schema_version": "artifact-provenance-v1",
            "generated_by": "backtrader-agent",
            "renderer_version": "scaffold-v1",
            "session_id": session_id,
            "artifact_hash": portable["artifact_hash"],
            "spec_hash": spec.spec_hash,
            "dataset_id": dataset["dataset_id"],
            "dataset_manifest_hash": dataset["manifest_hash"],
            "draft_relative_path": draft_relative,
            "manifest_sha256": sha256_bytes(manifest_path.read_bytes()),
        }
        record_payload["record_hash"] = hash_object(record_payload)
        record = {
            **record_payload,
            "signature": TokenAuthority(self.state_root).sign_product_record(
                record_payload
            ),
        }
        record_path = (
            self.state_root
            / "sessions"
            / session_id
            / "artifacts"
            / f"{portable['artifact_hash']}.json"
        )
        create_or_verify_json(
            record_path,
            record,
            conflict_code="BTAG-PROVENANCE-CONFLICT",
            conflict_message="artifact provenance record conflicts with the rendered bytes",
        )
        return {
            **portable,
            "_draft_path": str(draft_root),
            "_artifact_record_hash": record_payload["record_hash"],
        }
